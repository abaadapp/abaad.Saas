<?php

namespace App\Console\Commands;

use App\Support\Archive\Period;

/**
 * أرشيفُ الأسبوع المنقضي لكلّ متجر — يُجدول الاثنين، الساعةَ الرابعة.
 *
 * ═══ ولمَ الاثنينُ الرابعة ═══
 *
 * الأسبوعُ عندنا من الاثنين إلى الأحد (انظر `Period::weekStart`)، فأوّلُ
 * لحظةٍ يصحّ فيها أرشيفُه هي فجرُ الاثنين التالي.
 *
 * والرابعةُ لأنّ ما قبلها مشغول: النسخةُ التقنيّة في الثانية، وتنظيفُ
 * المهملات في الثانية والنصف، والأرشيفُ الشهريُّ في الثالثة. ولو وقعا معًا
 * لَتزاحم عاملان على القرص نفسِه وعلى الطابور نفسِه — ويقع ذلك حين يكون
 * أوّلُ الشهر يومَ اثنين، أي مرّةً كلَّ سبعة أشهر تقريبًا: أندرُ الحالات
 * وأسوأُها وقتًا.
 *
 * والسابعةُ بعدها لتقارير البريد، فبينهما ثلاثُ ساعاتٍ تكفي مئةَ متجر.
 */
class ArchiveWeekly extends ArchiveRun
{
    protected $signature = 'archive:weekly
        {--business= : معرّف متجر محدّد (اختياري)}
        {--week= : يومٌ في الأسبوع المطلوب بصيغة YYYY-MM-DD (افتراضيًّا: الأسبوع المنقضي)}';

    protected $description = 'طلبُ أرشيف الأسبوع المنقضي لكل المتاجر — يُبنى في الطابور';

    protected function type(): string
    {
        return Period::WEEKLY;
    }

    protected function periodOption(): string
    {
        return 'week';
    }
}
