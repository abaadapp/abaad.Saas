<?php

namespace App\Http\Middleware;

use App\Support\Permissions;
use App\Support\PosTerminal;
use Closure;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;

/**
 * فرع نقطة البيع يأتي من الجهاز، لا من الجلسة.
 *
 * كان الكاشير يرث الفرع الذي اختاره المدير في مبدّل الفروع — أو «كل الفروع»
 * فيسقط على أوّل فرعٍ في القائمة. وهذا يعني أن تبديلًا في تبويبٍ آخر (أو جلسةً
 * قديمة عالقة) ينقل مبيعات فرعٍ إلى فرعٍ آخر بلا إنذار، ولا يُكتشف إلا عند
 * جرد آخر الشهر.
 *
 * والضبط في كل طلب لا عند الدخول وحده: الجلسة واحدة بين تبويب الإدارة وتبويب
 * الصندوق، فما يكتبه ذاك يقرأه هذا بعد لحظة.
 *
 * ولوحة الإدارة تبقى على حالها — «كل الفروع» عرضٌ مشروع فيها. الحظر هنا على
 * البيع وحده: البيعة تقع في فرعٍ بعينه أو لا تقع.
 *
 * وهنا يُفرض إسناد الفرع كذلك.
 *
 * كان يُفرض عند الدخول بالرمز: من لا يعمل في فرع الجهاز يُردّ عند لوحة
 * الأرقام. ولمّا رُفع ذلك الباب بقي الفرض بلا موضع — فكاشير الخوير يدخل
 * ببريده على جهاز السيب ويبيع عليه، وهو العطب نفسه الذي أُصلح يوم صار
 * `users.branch` قائمةَ إسنادٍ تُفحص. فانتقل الفرض إلى هنا: يُقاس في كل
 * طلبٍ لا مرّةً عند الباب.
 */
class BindPosBranch
{
    public function handle(Request $request, Closure $next)
    {
        $branchId = PosTerminal::branchId();

        if (! $branchId) {
            return $next($request);
        }

        $user = Auth::user();

        if ($user && ! $user->worksAt($branchId)) {
            /*
             * ═══ وسببان يقعان على هذا السطر، لا سبب ═══
             *
             * إمّا أنّ الجهاز صندوقُ متجرٍ آخر، أو أنّه صندوقُ متجره في فرعٍ
             * لم يُسنَد إليه. والجوابُ يفترق: الأوّل يُنسى الجهازُ من شاشة
             * الدخول، والثاني يُراجَع فيه مديرُه. ورسالةٌ واحدةٌ لهما تبعث
             * صاحبَ المتجر يبحث عن صلاحيّةٍ ناقصةٍ وعطبُه في الجهاز.
             */
            $device = PosTerminal::current();
            $foreign = $device && (int) $device->business_id !== (int) $user->business_id;

            $why = $foreign
                ? __('هذا الجهاز صندوقٌ لمتجرٍ آخر — انسَه ليفتح صندوقُ متجرك عليه.')
                : __('هذا الجهاز يعمل على فرعٍ لست مُسنَدًا إليه. راجع مديرك.');

            /*
             * ═══ والخروجُ لمن لا بابَ له سوى الصندوق ═══
             *
             * الكاشيرُ صفحتُه الرئيسيّة نقطةُ البيع نفسُها، فردُّه إليها يدور
             * بلا نهاية — ولهذا يُنهى جلسته ويُقال له السببُ عند الباب.
             *
             * أمّا من له لوحةٌ يفتحها فالخروجُ يضرّه ولا يحرس شيئًا: جلستُه
             * صحيحةٌ في متجره كلِّه، فتُهدَم لأجل شاشةٍ واحدةٍ لا يحتاجها.
             *
             * وأسوأُ من ذلك أنّها **مصيدة**: الخروجُ يحفظ الوجهةَ المقصودة،
             * فيدخل من جديدٍ فيُردّ إلى `/pos` فيُخرَج ثانيةً — دورةٌ لا مخرجَ
             * منها إلّا زرٌّ رماديٌّ أسفلَ شاشة الدخول لا يعرفه أحد. وقد وقعت
             * على صاحب متجرٍ حقيقيّ: جهازُ متجرٍ على هاتفه، وحسابُ متجرٍ آخر.
             *
             * فمن له بابٌ غيرُه يُردّ إليه بجلسته قائمة، وتُمحى الوجهةُ
             * المحفوظة لئلّا تُعيده الدورةُ عند أوّل دخول.
             */
            $home = Permissions::homeFor($user);

            if ($home !== route('pos.index')) {
                $request->session()->forget('url.intended');

                /*
                 * ═══ والمخرجُ يُعطى في اليد، لا يُشار إلى شاشةٍ أخرى ═══
                 *
                 * «اضغط ليس هذا متجرك؟ في شاشة الدخول» تُقال لمن **في** شاشة
                 * الدخول. أمّا الداخلُ إلى لوحته فلا يبلغ ذلك الزرَّ إلّا أن
                 * يخرج من النظام كلِّه ثمّ يعود — وهو ما فعلناه بالضبط حين
                 * كُفّ عنه الطرد. فيبقى يضغط «نقطة البيع» ويُردّ كلَّ مرّة.
                 *
                 * والنسيانُ يمحو ارتباطَ هذا المتصفّح وحدَه — لا يمسّ صفَّ
                 * الجهاز ولا صندوقَ المتجر الذي يملكه (`PosTerminal::forget`
                 * تُسقط الكعكة لا الصفّ). فيُعرض زرًّا في التنبيه نفسِه.
                 *
                 * وفرعٌ في متجره لم يُسنَد إليه لا زرَّ له: ذاك إسنادٌ يُصلحه
                 * مديرُه، ونسيانُ الجهاز فيه يفكّ صندوقًا قائمًا لمتجره هو.
                 */
                $toast = ['msg' => $why, 'type' => 'warning'];

                if ($foreign) {
                    $toast['msg'] = __('هذا الجهاز صندوقٌ لمتجرٍ آخر. انسَه ليفتح صندوقُ متجرك على هذا الجهاز.');
                    $toast['confirm'] = [
                        'url' => route('device.forget'),
                        'method' => 'post',
                        'label' => __('انسَ هذا الجهاز'),
                    ];
                }

                return redirect($home)->with('toast', $toast);
            }

            Auth::logout();
            $request->session()->invalidate();
            $request->session()->regenerateToken();

            /*
             * ═══ والكاشيرُ كذلك يُعطى المخرجَ في يده ═══
             *
             * كانت الرسالةُ تحيله إلى رابطٍ رماديٍّ أسفل شاشة الدخول: «ليس
             * هذا متجرك؟». ووقعت على موظّفٍ حقيقيّ — دخل ببريده الصحيح
             * وكلمته الصحيحة، فأُخرج عند الباب مرّةً بعد مرّة، وظنّ صاحبُ
             * المتجر أنّ كلمة المرور هي العطب فأعاد تعيينها مرارًا.
             *
             * فيُعلَّم البابُ أنّ السببَ جهازُ متجرٍ آخر، فتعرض الشاشةُ زرًّا
             * في الرسالة نفسِها. والنسيانُ يمحو ارتباطَ هذا المتصفّح وحدَه.
             */
            return redirect()->route('login')
                ->withErrors(['email' => $why])
                ->with('foreign_device', $foreign);
        }

        session(['current_branch' => $branchId]);

        /*
         * ختمُ آخر ظهور كان يُكتب عند الدخول بالرمز، فلمّا رُفع بقي عمود
         * `last_seen_at` جامدًا وشاشة الأجهزة تقول عن صندوقٍ يبيع اليوم إنه
         * لم يُرَ منذ أسابيع. ويُكتب بفاصلٍ لا مع كل طلب: نقطة البيع تنادي
         * الخادم عشرات المرّات في الدقيقة، وكتابةُ صفٍّ لكل نداء ثمنٌ بلا
         * مقابل — والدقّة إلى الدقيقة تكفي «آخر ظهور».
         */
        if ($device = PosTerminal::current()) {
            if (! $device->last_seen_at || $device->last_seen_at->lt(now()->subMinute())) {
                PosTerminal::touch($device);
            }
        }

        return $next($request);
    }
}
