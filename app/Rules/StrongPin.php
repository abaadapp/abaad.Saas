<?php

namespace App\Rules;

use Closure;
use Illuminate\Contracts\Validation\ValidationRule;

/**
 * رمز دخولٍ لا يُخمَّن من أوّل محاولة.
 *
 * فضاء الرموز عشرة آلاف، لكن من يجرّب لا يبدأ من 0000 ويعدّ: يبدأ بـ1234 ثم
 * 1111 ثم سنة ميلاد. وهذه العشرات الأولى تغطّي جزءًا كبيرًا ممّا يختاره
 * الناس فعلًا — فالحدّان (٥ في الدقيقة و٣٠ في الساعة) يكفيان لمسحها كلّها
 * في يومٍ واحد إن كان الرمز منها.
 *
 * والمنع عند الاختيار لا عند الدخول: الموظّف يقرأ سببه ويختار غيره، بدل أن
 * يُترك الباب مواربًا ثم يُلام حين يُفتح.
 *
 * وما يُمنع ~١٥٠ رمزًا من عشرة آلاف — أي أن فضاء الاختيار يبقى كما هو
 * عمليًّا، ويسقط منه ما يُجرَّب أولًا.
 */
class StrongPin implements ValidationRule
{
    /** أشهر ما يُختار — من إحصاءات رموزٍ مسرّبة، لا من تخمين */
    private const COMMON = [
        '1234', '1111', '0000', '1212', '7777', '1004', '2000', '4444',
        '2222', '6969', '9999', '3333', '5555', '6666', '1122', '1313',
        '8888', '4321', '2001', '1010', '1230', '1313', '1004', '2580',
    ];

    /** سبب الضعف، أو null إن كان الرمز صالحًا */
    public static function weakness(string $pin): ?string
    {
        if (! preg_match('/^\d{4}$/', $pin)) {
            return null; // شكلُه يحرسه شرطٌ آخر (digits:4)
        }

        if (in_array($pin, self::COMMON, true)) {
            return __('هذا من أكثر الرموز شيوعًا — يُجرَّب أولًا.');
        }

        // 0000، 1111 …
        if (preg_match('/^(\d)\1{3}$/', $pin)) {
            return __('الرقم نفسه أربع مرّات — اختر رمزًا غير مكرّر.');
        }

        // 1234 و4321: تسلسلٌ صاعد أو هابط
        $d = array_map('intval', str_split($pin));
        $up = $d[1] - $d[0] === 1 && $d[2] - $d[1] === 1 && $d[3] - $d[2] === 1;
        $down = $d[0] - $d[1] === 1 && $d[1] - $d[2] === 1 && $d[2] - $d[3] === 1;
        if ($up || $down) {
            return __('أرقام متتابعة — اختر رمزًا غير متسلسل.');
        }

        // 1212، 2323: زوجٌ مكرّر
        if (mb_substr($pin, 0, 2) === mb_substr($pin, 2, 2)) {
            return __('نصفان متطابقان — اختر رمزًا غير مكرّر.');
        }

        /*
         * سنوات الميلاد: 19xx و20xx.
         *
         * وهي أكثر ما يختاره الناس بعد المتتابع، وأسهلها على من يعرف صاحبها
         * — والموظّف يعرف زملاءه.
         */
        if (preg_match('/^(19|20)\d{2}$/', $pin)) {
            return __('يشبه سنة ميلاد — وهي أوّل ما يُجرَّب على من يعرفك.');
        }

        return null;
    }

    public function validate(string $attribute, mixed $value, Closure $fail): void
    {
        $reason = is_string($value) ? self::weakness($value) : null;

        if ($reason !== null) {
            $fail($reason);
        }
    }
}
