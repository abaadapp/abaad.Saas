<?php

namespace App\Support;

/**
 * اسمُ قسم الكتالوج كما يُعرض — بلغة الشاشة التي تعرضه.
 *
 * ═══ ولمَ لا `Demo::ln` ═══
 *
 * `ln` تردّ العربيّ متى فرغ `name_en`. وأغلبُ الأقسام فارغتُه: ما أُنشئ قبل
 * أن يملأه المعجمُ عند الحفظ، وما جاء من الإعداد الأوّل أو الاستيراد. فكانت
 * الواجهةُ الإنجليزيّة تعرض «منتجات» و«عروض» — ألفاظًا يعرفها `Lexicon`
 * يقينًا ولا يُسأل عنها.
 *
 * و`ln` تخدم أسماءَ الزبائن أيضًا (`customerLabel`)، واسمُ شخصٍ لا يُمرَّر
 * على معجم. فالقاعدةُ هنا للأقسام وحدها، لا تبديلٌ عامّ.
 *
 * ═══ الترتيب ═══
 *
 *   العربيّة ← الاسمُ كما كتبه التاجر.
 *   الإنجليزيّة ← `name_en` إن كتبه، ثمّ `Lexicon` إن عرف كلَّ لفظٍ في
 *   الاسم، ثمّ الاسمُ كما كُتب. فلا ترجمةَ مخترَعة لـ«باقات المناسبات».
 *
 * ولا كتابةَ في الجدول: الترجمةُ عند العرض وحده، وما في `name_en` يبقى ما
 * كتبه التاجر أو ما ملأه الحفظ. والقيمةُ التي يُرشَّح بها — الاسمُ في نقطة
 * البيع والمعرّفُ في الموقع — لا تمرّ من هنا.
 */
final class CategoryName
{
    public static function display(?string $name, ?string $nameEn, string $locale): string
    {
        $name = (string) $name;

        if ($locale !== 'en') {
            return $name;
        }

        /*
         * و«اسمٌ إنجليزيّ» كلُّه عربيّ ليس ترجمة: نُسخ فيه الاسمُ العربيّ
         * فيُعرض عربيًّا في الصفحة الإنجليزيّة. فيُترك ويُسأل المعجم — وما
         * كتبه التاجرُ بحروفٍ لاتينيّة يبقى كما كتبه. ولا يُكتب شيءٌ في القاعدة.
         */
        if (filled($nameEn) && ! self::arabicOnly((string) $nameEn)) {
            return (string) $nameEn;
        }

        return Lexicon::translate($name) ?? $name;
    }

    /** حروفٌ عربيّة ولا حرفَ لاتينيًّا واحدًا */
    private static function arabicOnly(string $text): bool
    {
        return preg_match('/\p{Arabic}/u', $text) === 1 && preg_match('/[A-Za-z]/', $text) === 0;
    }
}
