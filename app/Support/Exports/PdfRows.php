<?php

namespace App\Support\Exports;

use Illuminate\Http\Response;

/**
 * ورقةُ PDF تحمل كلَّ ما طابق — أو تُرفض بكلامٍ يُقرأ. لا ثالث.
 *
 * كانت ورقةُ مركز التقارير تقف عند سقف الشاشة (خمسمئة) وتكتب ذلك في
 * أسفلها، والقوائمُ تُطبع كاملةً مهما طالت. والورقةُ المطبوعة تُقرأ على
 * أنّها الكلّ: من أخذها إلى اجتماعٍ لا ينظر في سطرها الأخير.
 *
 * فالآن: ما دون `MAX` يُطبع كاملًا، وما فوقه يُرفض قبل أن يُبنى — mpdf
 * يبني الورقة كلَّها في الذاكرة، وآلافُ الصفحات تُسقط الطلب بعد دقائق
 * بلا كلمة. ويُدلّ على Excel وCSV، وهما بلا سقف.
 */
final class PdfRows
{
    /**
     * أكثرُ ما تحمله ورقةُ PDF واحدة من صفوف.
     *
     * ثلاثةُ آلاف صفٍّ قرابةُ مئة صفحة A4 — أكثرُ ممّا يُطبع ويُقرأ، وأقلُّ
     * ممّا يُتعب الخادم.
     */
    public const MAX = 3000;

    /** الرفضُ إن زادت الصفوف — وإلّا null فتُطبع الورقة كاملة */
    public static function refuse(int $rows): ?Response
    {
        if ($rows <= self::MAX) {
            return null;
        }

        return response()->view('pdf.too-large', [
            'message' => __('النتائج كبيرة جدًا لتصدير PDF، استخدم Excel أو CSV.'),
            'detail' => __('عدد النتائج :rows وحدُّ ورقة PDF :max — ضيّق المرشّحات أو صدّر Excel أو CSV ففيهما النتائج كلُّها.', [
                'rows' => number_format($rows),
                'max' => number_format(self::MAX),
            ]),
        ], 422);
    }
}
