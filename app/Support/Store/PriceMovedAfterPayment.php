<?php

namespace App\Support\Store;

/**
 * قُبض المالُ، ثمّ تبدّل المبلغُ قبل أن يُكتب الطلب.
 *
 * ═══ ولمَ استثناءٌ على حدة ═══
 *
 * `place` تردّ الطلبَ لأسبابٍ كثيرة، وجوابُها يفترق:
 *
 *   نفد الصنفُ بين الدفع والتصديق — يجهّز صاحبُ المحلّ بديلًا أو يردّ
 *   المال، وكلاهما قرارُه هو. فتبقى الدفعةُ معلَّقةً ويُوقَظ في جرسه، وهذا
 *   قرارٌ مكتوبٌ في `PaymobController::settle` منذ أوّل يوم.
 *
 *   أمّا أن يتبدّل **المبلغُ** فلا قرارَ فيه: الزبونُ وافق على سعرٍ ودفعه،
 *   ولا يجوز أن يُكتب له طلبٌ بغيره ولا أن يُحتجز مالُه على طلبٍ لن يُكتب.
 *   فيُردّ المالُ من نفسه.
 *
 * فيُميَّز بنوعه لا برسالته: مطابقةُ نصٍّ عربيٍّ لتقرير الردّ الماليّ تكسر
 * يومَ يُحرَّر حرفٌ في الرسالة.
 */
class PriceMovedAfterPayment extends \RuntimeException
{
    public function __construct(
        /** ما قُبض، بأصغر وحدة */
        public readonly int $charged,
        /** وما صار إليه التسعير، بأصغر وحدة */
        public readonly int $now,
    ) {
        parent::__construct(sprintf('تبدّل المبلغ بعد الدفع: قُبض %d وصار %d', $charged, $now));
    }
}
