<?php

namespace App\Support\Store;

/**
 * أصولُ الواجهة ببصمةٍ تتغيّر حين يتغيّر الملفّ.
 *
 * ═══ العطبُ الذي تعالجه ═══
 *
 * الشعارُ والأيقونةُ وورقةُ الخطّ ملفّاتٌ ساكنة يخدمها nginx بعنوانٍ ثابت.
 * ولا `Cache-Control` عليها — فيُعمِل المتصفّحُ قاعدةَ التخمين: يحتفظ بها
 * مدّةً تساوي عُشرَ عمرها منذ آخر تعديل. فملفٌّ عمرُه شهران يُحتفَظ به
 * **ستّة أيّام**.
 *
 * وهو نافعٌ ما دام الملفّ لم يتغيّر. فإذا بُدِّل الشعارُ بقي الزائرُ
 * العائد يرى القديمَ أيّامًا — والعنوانُ هو هو، فلا شيء يقول للمتصفّح
 * إنّ خلفه ملفًّا آخر.
 *
 * والبصمةُ تحلّه بلا أن تمسّ خادمًا: العنوانُ يتغيّر فيُطلب من جديد،
 * والقديمُ يبقى في ذاكرة من لم يعد. وnginx لا يرى الاستفهامَ أصلًا —
 * `$uri` لا يشمله — فيخدم الملفَّ نفسَه.
 *
 * ولا تُستعمل لأصول `Vite`: تلك مبصومةٌ في اسمها أصلًا وتُخدَم
 * `immutable`، وبصمةٌ فوق بصمةٍ عبث.
 */
final class StoreAsset
{
    /**
     * بصماتُ هذا الطلب.
     *
     * و`filemtime` نداءُ نظام: الصفحةُ تذكر الشعارَ مرّتين (الترويسة
     * والذيل)، فبلا حفظٍ يُسأل القرصُ مرّتين عن ملفٍّ واحد.
     *
     * @var array<string, string>
     */
    private static array $stamps = [];

    /** العنوان ببصمته — وكما هو إن لم يكن له ملفٌّ عندنا */
    public static function url(string $path): string
    {
        $stamp = self::$stamps[$path] ??= self::stamp($path);

        return $stamp === '' ? $path : $path.'?v='.$stamp;
    }

    /**
     * بصمةُ الملفّ من زمن تعديله — لا من محتواه.
     *
     * قراءةُ ملفٍّ كاملًا لتُهشَّم في كلّ طلبٍ ثمنٌ لا يشتري شيئًا هنا:
     * الملفُّ لا يتغيّر إلّا بنشرةٍ تُبدّل زمنَه. و`md5` لأنّ الزمنَ نفسَه
     * يقول متى نُشر الخادم، ولا حاجة لأن يُقال.
     */
    private static function stamp(string $path): string
    {
        $file = public_path(ltrim((string) parse_url($path, PHP_URL_PATH), '/'));

        return is_file($file) ? substr(md5((string) filemtime($file)), 0, 8) : '';
    }
}
