<?php

namespace App\Support;

use Illuminate\Http\Request;
use Inertia\Inertia;

/**
 * تبدُّلُ المتجر الجالسِ على الجلسة — بلا أن يرث ما تركه سابقُه.
 *
 * ═══ ما كان يقع ═══
 *
 * مديرُ المنصّة يدخل متجر A ثمّ يخرج ويدخل B **في المستند نفسِه**
 * (`router.post`). والجلسةُ كما هي: تحمل ما كتبه A فيها — ملفَّ استيرادٍ
 * معلَّقًا برقمِ فرعٍ من فروع A، وفرعًا مختارًا، وعملةَ عرض، وكاشيرًا —
 * فيُكمل B استيرادًا بدأه A ويُكتب مخزونُه على فرعٍ يملكه A. وسجلُّ المتصفّح
 * كما هو: «رجوع» يعرض شاشاتِ A كاملةً وهو في جلسة B.
 *
 * ═══ والقاعدة: ما لا يُنقل صراحةً لا يُنقل ═══
 *
 * تُفرَّغ الجلسةُ كلُّها ويُبقى ما في `CARRY` وحده — تفضيلُ الجالس لا بيانُ
 * متجر. فمفتاحٌ يُضاف غدًا لاستيرادٍ جديد لا يتسرّب لأنّ أحدًا نسي أن يذكره
 * هنا: الأصلُ المنعُ لا الإذن.
 *
 * ويُجدَّد معرّفُ الجلسة ورمزُ الحماية، ويُطلب من المتصفّح مسحُ سجلّه.
 */
final class TenantSwitch
{
    /** ما يعبر التبدّلَ: لغةُ من يجلس أمام الشاشة — لا شيءَ من متجر */
    public const CARRY = ['locale'];

    /** يُنادى **قبل** `Auth::login` — التفريغُ بعده يُخرج من دخل للتوّ */
    public static function reset(Request $request): void
    {
        $session = $request->session();
        $carry = $session->only(self::CARRY);

        $session->flush();
        $session->put($carry);
        $session->regenerate();

        Inertia::clearHistory();
    }
}
