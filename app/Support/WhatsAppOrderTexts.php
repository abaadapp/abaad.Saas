    /** نصٌّ بلغة الزبون، وما فيه من `:مفتاح` يُملأ — والمفتاحُ الغائبُ عطبٌ يُرى في الاختبار */
    public static function say(string $lang, string $key, array $replace = []): string
    {
        $text = ($lang === 'en' ? self::EN : self::AR)[$key] ?? null;

        if ($text === null) {
            throw new \InvalidArgumentException("Unknown WhatsApp order text: {$key}");
        }

        // الأطولُ أوّلًا: `:product` لا يُكسر بـ`:p`
        uksort($replace, fn ($a, $b) => mb_strlen((string) $b) <=> mb_strlen((string) $a));

        foreach ($replace as $name => $value) {
            $text = str_replace(':'.$name, (string) $value, $text);
        }

        return $text;
    }

    /** المفاتيحُ في اللغتين — لحارسٍ يسأل أنّ لا نصَّ ناقصٌ في إحداهما */
    public static function keys(string $lang): array
    {
        return array_keys($lang === 'en' ? self::EN : self::AR);
    }

    /** قصٌّ لحدّ ميتا بلا كسر حرفٍ عربيّ — والنقاطُ تقول إنّه قُصّ */
    public static function fit(string $text, int $max): string
    {
        $text = trim(preg_replace('/\s+/u', ' ', $text) ?? $text);

        return mb_strlen($text) <= $max ? $text : rtrim(mb_substr($text, 0, $max - 1)).'…';
    }
