 *
 * وmergeConfigFrom يدمج المفاتيح العليا وحدها، فمصفوفة pages تُستبدل كاملةً
 * ولا تُدمج — لذا تُكتب امتداداتها هنا معها ولا تُترك للحزمة.
 */
return [

    'pages' => [

        'ensure_pages_exist' => false,

        'paths' => [

            resource_path('js/Pages'),

        ],

        'extensions' => [

            'js',
            'jsx',
            'svelte',
            'ts',
            'tsx',
            'vue',

        ],

    ],

    /*
     * سجلُّ المتصفّح مشفَّرٌ — لأنّ فيه متجرًا كاملًا.
     *
     * Inertia تحفظ في `history.state` **خصائصَ الصفحة كلَّها**: الموظّفين
     * والمسمّيات والأرقام. وزرُّ «رجوع» يستعيدها من هناك **بلا سؤال الخادم**.
     * فمديرُ المنصّة الذي دخل متجر A ثمّ خرج ودخل B كان يضغط «رجوع» فيرى
     * شاشةَ «إضافة موظّف» لمتجر A بمسمّياته — وهو في جلسة B. قِسناه في متصفّحٍ
     * حقيقيّ: صفرُ طلبات إلى الخادم، والمسمّى المخترَع ظاهر.
     *
     * والتشفيرُ وحده لا يكفي: مفتاحُه في `sessionStorage` يعيش ما عاش
     * التبويب. فيُمسح عند كلّ تبدّلٍ للهويّة (`TenantSwitch`، ومستمعُ `Login`
     * في `AppServiceProvider`، ومراقبُ الواجهة `lib/identity-history`) —
     * فيعجز «رجوع» عن فكّ ما كُتب لغير الجالس الآن، ويسأل الخادمَ من جديد.
     *
     * ولا `env` له عمدًا: بابٌ يُطفأ بسطرٍ في ملفّ الخادم يعيد التسريب بلا
     * أثرٍ في السجلّ. وعلى عنوانٍ بلا SSL تتركه الحزمةُ مكشوفًا وتحذّر في
     * الطرفيّة ولا تنكسر — والإنتاجُ على HTTPS.
     */
    'history' => [

        'encrypt' => true,

    ],

];
