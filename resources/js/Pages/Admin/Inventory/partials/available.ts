/** صنفٌ كما ترسله شاشة التعديلات — الإجماليّ ورصيد كل فرع */
export interface StockedOption {
    /** إجماليّ الشركة: مجموع الفروع */
    quantity: number;
    /** [معرّف الفرع => الكمية] — وصنفٌ لم يُوزَّع كلُّه في الفرع الأوّل */
    stock?: Record<number, number>;
}

/**
 * المتاح للخصم — رصيدُ الفرع المختار لا إجماليُّ الشركة.
 *
 * ═══ العطبُ الذي فُتح لأجله هذا الملفّ ═══
 *
 * كانت شاشةُ التعديلات تقرأ `product.quantity` — وهو مجموعُ الفروع —
 * وتقيس عليه حدَّ الخصم، **والكتابةُ تقع على فرعٍ بعينه**. قِستُها في
 * المتصفّح: باقةٌ رصيدُها كلُّه في الرئيسيّ (٣٢) وصفرٌ في صلالة — تُختار
 * صلالة فتقول الشاشةُ «المتوفّر: ٣٢»، ويُقدَّر أثرُ التلف بثلاثين ريالًا،
 * ويفتح زرُّ التسجيل. ثمّ يردّ الخادمُ «رصيد فرع صلالة من هذا الصنف 0 فقط».
 *
 * وهو عطبُ الخادم نفسُه الذي أُصلح في `StockAdjustmentController::store` —
 * «الحارسُ يقيس إجماليّ الشركة والكتابةُ تقع على فرعٍ بعينه» — وبقي على
 * الشاشة بعده. ورقمٌ في وجه التاجر يخالف ما سيفعله الخادم أسوأ من لا رقم:
 * عليه يقرّر كم يُتلف.
 *
 * ═══ وبلا فرعٍ مختار يُقرأ الإجماليّ ═══
 *
 * لا صفرًا: زرُّ التسجيل مغلقٌ حينها أصلًا (الفرع حقلٌ مطلوب)، وقولُ «صفر»
 * عن صنفٍ عند صاحبه منه اثنان وثلاثون كذبٌ لا حراسة.
 *
 * @param branchId قيمة الحقل كما هي في النموذج — نصٌّ أو فراغ
 */
export function availableIn(product: StockedOption | undefined, branchId: string): number {
    if (!product) {
        return 0;
    }

    const branch = parseInt(branchId, 10);

    return Number.isNaN(branch) ? product.quantity : (product.stock?.[branch] ?? 0);
}
