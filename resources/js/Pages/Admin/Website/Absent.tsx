import { Globe } from 'lucide-react';
import AdminLayout from '@/Layouts/AdminLayout';
import PageHeader from '@/Components/PageHeader';
import Gate from '@/Components/Gate';
import { useTranslate } from '@/lib/i18n';

/**
 * «الموقع الإلكتروني» لموظّفٍ لا يملك ضبطَه في متجرٍ بلا موقع.
 *
 * ═══ العطب ═══
 *
 * قسمُ `website` يُمنح للموظّف ليتفقّد منتجات موقعه — وشاشةُ إنشاء الموقع
 * فعلُ صاحب المتجر وحدَه، فتُحرَس بـ`WEBSITE_CONFIGURE`. فمن مُنح القسم في
 * متجرٍ لم يُنشئ موقعَه بعد يجد البابَ في شريطه الجانبيّ، ويُصفع عند
 * الضغط بصفحةِ ٤٠٣ سوداء لا تقول له شيئًا يفعله.
 *
 * والحارسُ صحيح: لا يجوز أن يكتب موقعًا من لا يملك ذلك. الخطأُ أنّ الرفضَ
 * كان يخرج بلغة الخادم لا بلغة من يقرؤه.
 *
 * ═══ ولمَ لا يُخفى البابُ بدل ذلك ═══
 *
 * إخفاؤه يعني أن يسأل الشريطُ الجانبيّ عن **وجود موقع** في كلّ فتحة — شرطٌ
 * من البيانات يدخل قائمةً تُبنى من الأقسام وحدها. والأهمُّ أنّ الموظّف
 * حينها لا يعرف أنّ للمتجر موقعًا يمكن أن يكون، فيسأل: «أين قسمُ الموقع
 * الذي أُخبرت أنّي أملكه؟»
 *
 * فالبابُ يبقى، ويقول ما وراءه ومن يفتحه.
 */
export default function WebsiteAbsent() {
    const t = useTranslate();

    return (
        <AdminLayout title="الموقع الإلكتروني">
            <PageHeader title="الموقع الإلكتروني" subtitle={t('موقع متجرك على الإنترنت')} />

            <Gate
                icon={Globe}
                title="لم يُنشأ موقع هذا المتجر بعد"
                description="حين يُنشأ ستجد هنا صفحاته ومنتجاته وطلباته."
                note={t('إنشاء الموقع لصاحب المتجر — اطلبه منه.')}
            />
        </AdminLayout>
    );
}
