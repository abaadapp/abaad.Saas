/**
 * تبويباتُ محرّر الواجهة — ترتيبٌ للعين لا قاعدة.
 *
 * ═══ ما لا تفعله ═══
 *
 * لا تُرسَل ولا تُحفظ، ولا تُضيف حقلًا ولا تُسقط حقلًا: الصفوفُ وحقولُها
 * ومفاتيحُها كما يرسلها الخادم (`PageEditor::rows`)، والحفظُ والمسوّدةُ
 * والنشرُ كما كانت. التبويبُ يختار أيَّ صفوفٍ تُرسم الآن — والقيمُ في
 * النموذج نفسِه، فلا يضيع ما كُتب حين يُبدَّل التبويب.
 *
 * ═══ وكلُّ صفٍّ في تبويبٍ واحد ═══
 *
 * الأقسامُ التي تُرتَّب (غير الثابتة) في «الرئيسية» دائمًا، بترتيبها.
 * والثابتةُ بمفاتيحها أدناه، وما لا تعرفه هذه القائمةُ — صفٌّ يُضاف غدًا —
 * يقع في «متقدّمة»، فلا يغيب صفٌّ عن الشاشة يوم يُضاف.
 *
 * ═══ ولمَ «الصفحات والقائمة» تبويبٌ واحد ═══
 *
 * الصفحاتُ المخصّصة تُكتب في عناصر القائمة نفسِها (`MenuField`، والمفتاحان
 * يُحفظان معًا). فقسمتُهما على تبويبين تعني نسختين من حقلٍ واحد تكتب كلٌّ
 * منهما فوق أختها — فيبقيان معًا كما يحفظهما النظام.
 */

export type EditorTabId = 'home' | 'pages' | 'links' | 'identity' | 'contact' | 'advanced';

export interface EditorTab {
    id: EditorTabId;
    label: string;
    hint: string;
}

export const EDITOR_TABS: EditorTab[] = [
    { id: 'home', label: 'الرئيسية والأقسام', hint: 'الواجهة أعلى الصفحة، ثمّ أقسام الرئيسية — رتّبها بالسهمين وأخفِ ما لا تريده بالعين.' },
    { id: 'pages', label: 'الصفحات والقائمة', hint: 'عناصر القائمة الرئيسية وصفحاتك المخصّصة — كلُّ صفحةٍ تُكتب في عنصرها.' },
    { id: 'links', label: 'المتجر والروابط', hint: 'شريط الإعلان واختصارات المتجر، ومجموعاتك، والشريط المصوّر.' },
    { id: 'identity', label: 'الهوية والصور', hint: 'طريقة عرض صور المنتجات والفئات.' },
    { id: 'contact', label: 'التواصل والتذييل', hint: 'أعمدة التذييل وسطره الأخير، وواتساب وإنستغرام وساعات العمل.' },
    { id: 'advanced', label: 'إعدادات متقدمة', hint: 'خياراتٌ تُضبط مرّةً — مثل «أضف مع طلبك» في صفحة المنتج.' },
];

/** الصفوفُ الثابتة وتبويبُ كلٍّ منها — بمفاتيح `PageEditor` (HEAD، HERO، FOOT…) */
export const FIXED_ROW_TAB: Record<string, EditorTabId> = {
    hero: 'home',
    menu: 'pages',
    head: 'links',
    collections: 'links',
    vbar: 'links',
    images: 'identity',
    foot: 'contact',
    upsells: 'advanced',
};

/** تبويبُ صفّ — القسمُ الذي يُرتَّب في «الرئيسية»، والمجهولُ في «متقدّمة» */
export function tabOf(row: { key: string; fixed: boolean }): EditorTabId {
    if (! row.fixed) return 'home';

    return FIXED_ROW_TAB[row.key] ?? 'advanced';
}

/** نصٌّ للبحث بلا تشكيلٍ ولا همزات — «الواجهه» تجد «الواجهة»، و«اضف» تجد «أضف» */
export function searchable(text: string): string {
    return text
        .toLowerCase()
        .replace(/[ً-ْٰـ]/g, '')
        .replace(/[أإآٱ]/g, 'ا')
        .replace(/ى/g, 'ي')
        .replace(/ة/g, 'ه')
        .replace(/\s+/g, ' ')
        .trim();
}
