/**
 * «تم» على لوحة مفاتيح الآيباد تُنهي الكتابة، ولا تحفظ.
 *
 * المتصفّحات ترسل النموذج حين تُضغط Enter داخل حقلٍ فيه — «الإرسال الضمني».
 * على سطح المكتب هذا متوقَّع: يد المستخدم على المفاتيح ويعرف أنه ضغط Enter.
 * وعلى الآيباد ليس كذلك: المفتاح مكتوبٌ عليه «تم»، وهي كلمةٌ تعني إنهاءَ
 * الكتابة في الخانة لا حفظَ النموذج. فيكتب التاجر اسم المنتج، يضغط «تم»
 * ليغلق اللوحة ويكمل بقيّة الحقول، فيُحفظ المنتج ناقصًا — وقد أُنشئ سجلٌّ
 * لا يريده أحد.
 *
 * فعلى الأجهزة اللمسية وحدها: Enter داخل حقلٍ تُنهي التركيز فقط، والحفظ
 * يبقى بضغطة الزرّ. وسطح المكتب لا يتغيّر.
 *
 * ═══ والحقلُ خارج النموذج حقلٌ مثلُه ═══
 *
 * كان الشرط `if (!el.form) return` — فما لا نموذجَ له لا يُمسّ. وكان ذلك
 * صحيحًا لو أنّ الغرض منعُ الإرسال الضمنيّ وحده؛ لكنّ الغرض الثاني — وهو
 * ما يراه صاحبُ المحلّ — أن **تنغلق اللوحة**. وبلا نموذجٍ لا تنغلق: يضغط
 * «تم» فلا يقع شيء، وتبقى اللوحة تغطّي نصفَ الآيباد حتى ينقر في فراغ
 * الصفحة إن وجد فراغًا.
 *
 * ومسحُ المستودع أخرج **١٧٤ حقلًا خارج أيّ نموذج** في أربعةٍ وخمسين ملفًّا،
 * وأكثرُها في الشاشات التي يُكتب فيها أكثرُ الكلام: فاتورة العميل، وأمر
 * الشراء، ونافذة الدفع. فالقاعدة صارت على الحقل لا على نموذجه.
 *
 * ثلاثة استثناءات مقصودة:
 * — النماذج التي تحمل `data-enter-submits`: الدخول والرمز واستعادة كلمة
 *   المرور. حقلٌ أو حقلان و«اذهب» على المفتاح، والمنعُ فيها إزعاجٌ لا حماية.
 * — ما استهلك المفتاح قبلنا (defaultPrevented): حقل الباركود يقرأ Enter من
 *   الماسح، وحقل الكوبون يطبّقه. المستمع في الفقاعة فيصل بعد React. وهذا
 *   الاستثناء يحرس الماسح: كاشيرٌ يمسح صنفًا بعد صنف لا يحتمل أن يفقد
 *   الحقلُ تركيزَه بعد كلّ مسحة.
 * — textarea: Enter فيها سطرٌ جديد ولا تُرسل نموذجًا أصلًا.
 */

/**
 * أزرارٌ لا يُكتب فيها — فلا لوحةَ تُغلق ولا تركيزَ يُنهى.
 *
 * وتُترك على حالها: Enter عليها تضغطها، ومنعُ ذلك يجعل زرًّا لا يعمل.
 */
const BUTTONS = ['submit', 'button', 'reset', 'image'];

export function enterEndsTypingOnTouch(): void {
    if (!window.matchMedia?.('(hover: none) and (pointer: coarse)').matches) {
        return;
    }

    document.addEventListener('keydown', (event) => {
        if (event.key !== 'Enter' || event.defaultPrevented) return;

        const el = event.target;
        if (!(el instanceof HTMLInputElement)) return;
        // نموذجٌ أذِن لـEnter أن ترسله — ولا شأن لنا بمفتاحه
        if (el.form?.dataset.enterSubmits !== undefined) return;
        if (BUTTONS.includes(el.type)) return;

        event.preventDefault();
        el.blur();
    });
}
