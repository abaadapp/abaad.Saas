/**
 * أصبعٌ على الزجاج — أم مؤشّرٌ ولوحةُ مفاتيح؟
 *
 * سؤالٌ واحدٌ يُسأل في موضعين: هل تُغلق «تم» اللوحةَ بدل أن تقفز
 * (`lib/enter-key`)، وهل تُكبَّر أهدافُ اللمس إلى ما يبلغه الإبهام
 * (المحوّل `touch:` في `app.css`). وجوابان لسؤالٍ واحدٍ يفترقان يومَ
 * يُبدَّل أحدهما — فالجواب هنا مرّةً واحدة.
 *
 * ═══ ولمَ لا يكفي استعلامُ الوسائط ═══
 *
 * `(hover: none) and (pointer: coarse)` هو السؤالُ الصحيح، ويصدق على
 * الهاتف. ولا يصدق على الآيباد: سفاري عليه يفتح المواقع بوضع «عرض كموقع
 * حاسوب» افتراضًا منذ iPadOS 13، ويُخفي لمسَه عمدًا ليُرى حاسوبًا — فيردّ
 * `hover: hover` و`pointer: fine`.
 *
 * فكان الآيباد يُعامَل حاسوبًا في الاثنين: «تم» تقفز إلى الحقل التالي
 * واللوحةُ مفتوحة، وأزرارُ نقطة البيع بأربعين بكسلًا لا بأربعٍ وأربعين.
 *
 * وعددُ نقاط اللمس لا يُخفى في ذلك الوضع: يبقى خمسًا، ولذلك يُكشف به. ولا
 * حاسوبَ من Apple يبلّغ لمسًا — فالشرطان معًا آيبادٌ أو هاتفٌ طُلب له وضعُ
 * الحاسوب، لا سواهما.
 *
 * والشرطُ الثاني مقصورٌ على أجهزة Apple عمدًا: حاسوبٌ محمولٌ بشاشةٍ لمسيّة
 * تحته لوحةُ مفاتيحَ حقيقيّة وفأرة، وتكبيرُ أزراره ومنعُ Enter فيه إزعاجٌ
 * لا حماية.
 */
export function typesOnGlass(): boolean {
    if (window.matchMedia?.('(hover: none) and (pointer: coarse)').matches) {
        return true;
    }

    return (navigator.maxTouchPoints ?? 0) > 1 && /Macintosh/.test(navigator.userAgent);
}

/**
 * السمةُ التي يقرؤها المحوّل `touch:` — تُكتب على `<html>` مرّةً عند الإقلاع.
 *
 * ═══ ولمَ سمةٌ لا استعلامُ وسائطٍ وحده ═══
 *
 * `touch:` في `app.css` يقبل الاثنين: استعلامَ الوسائط لمن يصدق فيه، وهذه
 * السمةَ لمن لا يصدق. فالهاتفُ يأخذ مقاسَه قبل أن يعمل أيُّ سطرِ JS، ولا
 * ينتظر شيئًا؛ والآيبادُ يأخذه حين تُكتب السمة.
 *
 * وتُكتب قبل أوّل رسم: `app.tsx` يستدعيها قبل `createRoot`، فلا تُرى
 * الأزرارُ بمقاسِ سطح المكتب ثمّ تقفز.
 */
export function markTouchDevice(): void {
    if (typesOnGlass()) {
        // مكتوبةٌ حرفًا لا عبر `dataset.touch`: `app.css` يقرأ `[data-touch]`،
        // وحارسٌ يقابل النصّين — ولا يقابل صيغتين لاسمٍ واحد
        document.documentElement.setAttribute('data-touch', '');
    }
}
