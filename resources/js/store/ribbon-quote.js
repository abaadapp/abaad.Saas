/*
 * تسعيرةُ إتمام RIBBON — آخرُ ما طُلب وحده يُرسم، وصفُّ التوصيل يتبع طريقةَ الاستلام.
 *
 * ═══ ولمَ ملفٌّ لا سطورٌ في القالب ═══
 *
 * صفحاتُ RIBBON بلا حزمة Vite: سكربتُها داخل القالب، وما داخل `<script>`
 * في بليد لا يبلغه اختبار. وهنا قراران يُحرسان: أيُّ جوابٍ يُرسم حين
 * يتسابق جوابان، وأيُرسم صفُّ التوصيل أصلًا. فيُكتبان هنا، ويُضمَّن الملفُّ
 * في `checkout.blade.php` كما هو، ويستورده Vitest فيضغط عليه.
 *
 * ═══ والعطبان اللذان وُضع لأجلهما ═══
 *
 * ١) كان الملخّصُ يكتب «التوصيل: مجاني» لمن اختار الاستلام من المحلّ — رسمٌ
 *    صفرٌ لأنّه لا توصيلَ أصلًا، لا لأنّ التوصيلَ مجّانيّ. فالصفُّ لا يُرسم
 *    للاستلام، و«مجاني» لتوصيلٍ رسمُه صفرٌ حقًّا (فوق حدّ المجّانيّ، أو بلا
 *    رسمٍ في إعداده).
 *
 * ٢) وكانت كلُّ تسعيرةٍ تُرسم حين تعود، أيًّا كان ترتيبُ عودتها. فمن ضغط
 *    «توصيل» ثمّ «استلام» بسرعة قد تعود تسعيرةُ التوصيل آخرًا فتُرسم فوق
 *    الاستلام: رسمٌ على طلبٍ لا يُوصَّل، وإجماليٌّ على الزرّ غيرُ الذي سيُطلب.
 *    فكلُّ نداءٍ يُرقَّم، وجوابُ ما سبقه يُطرح — والزرُّ مقفلٌ حتّى يعود الأخير.
 *
 * ولا رقمَ يُحسب هنا: الرسمُ والإجماليُّ من الخادم مكتوبَين (`WebCheckout::quote`).
 */
window.RBQuote = (function () {
    /*
     * يلفّ نداءَ التسعير — `fetcher(args)` يردّ وعدًا بجواب الخادم.
     *
     * `run` يردّ الجوابَ إن كان لآخر نداء، و`null` إن سبقه نداءٌ أحدث: من
     * يقرأ `null` لا يرسم شيئًا، فالأحدثُ في طريقه. و`pending` صادقةٌ ما دام
     * آخرُ نداءٍ لم يعد — وبها يُقفل زرُّ التأكيد.
     */
    function latest(fetcher) {
        var seq = 0;
        var settled = 0;

        function run(args) {
            var mine = ++seq;

            var asked;
            try { asked = Promise.resolve(fetcher(args)); } catch (e) { asked = Promise.reject(e); }

            return asked
                .then(
                    function (q) { return done(mine, q); },
                    // وانقطاعٌ لا يُبقي الزرَّ مقفلًا للأبد — يُقال كأيّ ردّ
                    function () { return done(mine, { ok: false, errors: {} }); }
                );
        }

        function done(mine, q) {
            if (mine !== seq) return null;
            settled = mine;

            return q;
        }

        return {
            run: run,
            pending: function () { return settled !== seq; },
        };
    }

    /*
     * صفُّ التوصيل في الملخّص — من التسعيرة نفسِها لا من زرٍّ في الصفحة.
     *
     * و`q.fulfil` طريقةُ الاستلام التي سعّرها الخادم: هي الحَكَم، فلا يُرسم
     * صفٌّ لطريقةٍ غيرِ التي حُسب لها الإجماليّ.
     */
    function shipping(q, T) {
        if (!q || !q.ok || q.fulfil !== 'delivery') return { show: false, text: '' };

        return { show: true, text: q.delivery > 0 ? q.delivery_text : T.free };
    }

    return { latest: latest, shipping: shipping };
})();
