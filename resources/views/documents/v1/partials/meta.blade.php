{{--
    شريطُ التعريف — التواريخُ والمراجع في أعمدةٍ لا في قائمة.

    ═══ العطبُ الذي وُلد منه هذا الملفّ ═══

    كانت جدولًا بعمودين: عنوانٌ بعرض ٣٤٪ وقيمةٌ بعده. فأربعةُ حقولٍ تشغل
    أربعةَ أسطرٍ في ثلث الورقة، **ونصفُ السطر خالٍ في كلٍّ منها** — منطقةٌ
    ميّتةٌ بعرض راحةِ اليد تمتدّ من التاريخ إلى جدول الأصناف.

    وهي حقولٌ قصيرة: تاريخٌ ووسيلةُ دفعٍ وفرعٌ وموظّف — لا سطرَ فيها يتجاوز
    عشرين حرفًا. فمكانُها أعمدةٌ متجاورة، عنوانٌ صغيرٌ فوق قيمته، كما تفعل
    كلُّ فاتورةٍ تُقرأ.

    ═══ وأربعةٌ في السطر لا أكثر ═══

    ستّةُ حقولٍ في سطرٍ واحد تجعل كلَّ عمودٍ بعرض ثلاثة سنتيمترات، فينكسر
    «وسيلة الدفع» سطرين ويلتصق بجاره. فتُقسَّم على أسطرٍ من أربعة، وتُوزَّع
    بالتساوي: عمودٌ يتبع محتواه يجعل الشريطَ يعيد ترتيب نفسه كلّما تغيّر
    اسمُ موظّف.

    المتغيّر: `$cells` قائمةُ `['label' => ..., 'value' => ...]`.
--}}
@php
    $cells = array_values(array_filter($cells ?? [], fn ($c) => filled($c['value'] ?? null)));
    $rows = array_chunk($cells, 4);
@endphp

@if (count($cells) > 0)
    <table class="metastrip">
        @foreach ($rows as $row)
            <tr>
                @foreach ($row as $cell)
                    {{--
                        والعرضُ من عدد خلايا **السطر الأوّل** لا من سطره هو.

                        خمسةُ حقولٍ تعني أربعةً ثمّ واحدًا: لو أخذ الأخيرُ
                        عرضَ سطره لامتدّ عبر الورقة كلِّها، فيخرج «الموظف»
                        وحده بعرض ٢١ سنتيمترًا تحت أربعةِ أعمدةٍ ضيّقة.
                    --}}
                    <td style="width:{{ round(100 / max(1, count($rows[0])), 3) }}%">
                        <div class="eyebrow">{{ $cell['label'] }}</div>
                        <div dir="{{ \App\Support\Paper::dirOf($cell['value']) }}" class="sm bidi">{{ $cell['value'] }}</div>
                    </td>
                @endforeach

                {{-- وخلايا خاوية تُكمل السطر الناقص فتبقى الأعمدةُ محاذيةً لما فوقها --}}
                @for ($i = count($row); $i < count($rows[0]); $i++)
                    <td></td>
                @endfor
            </tr>
        @endforeach
    </table>
@endif
