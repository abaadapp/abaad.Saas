{{--
    بطاقاتُ الأطراف — «من» و«إلى» جنبًا إلى جنب.

    ═══ ولمَ صارت بطاقةً بعد أن كانت سطورًا ═══

    كانت سطورًا رماديّةً متجاورةً بلا أرضيّة، يفصل بينها عنوانٌ صغير. فإذا
    طال عنوانُ أحد الطرفين سطرين وقصر الآخرُ سطرًا واحدًا، اختلط العمودان
    على العين: لا حدَّ يقول أين انتهى المورّد وأين بدأ البائع إلّا بعدّ
    الأسطر.

    والأرضيّةُ الفاتحة ترسم الحدَّ بلا إطارٍ حول كلّ شيء — فتبقى الورقةُ
    مستندًا يُقرأ لا نموذجًا يُملأ، وهو شرطُ المواصفة: «الأطراف كـblocks لا
    كجدولٍ صارم». والحافّةُ من جهة البداية وحدها: خطٌّ بلون التاجر يربط
    البطاقتين بالمسطرة التي تفتتح الورقة.

    ═══ والبائعُ أوّلُ الطرفين ═══

    كلُّ ورقةٍ في النظام كانت تحمل طرفًا واحدًا — «فاتورة إلى» أو
    «المورّد» — فيبقى نصفُ السطر خاليًا، وتنزوي بياناتُ البائع خمسةَ أسطرٍ
    رماديّةٍ صغيرة في ركن الترويسة.

    وهو ترتيبٌ يخالف ما تفعله كلُّ فاتورةٍ تُقرأ: الترويسةُ تحمل الهويّة —
    شعارًا واسمًا — وما تحتها يحمل **الطرفين متقابلين**. فمن يراجع الورقة
    يجد «من» و«إلى» في مستوى بصريٍّ واحد بدل أن يبحث عن أحدهما في الحاشية.

    والاسمُ لا يتكرّر: الترويسةُ قالته، وهنا تفاصيلُ الاتّصال وحدها تحت
    عنوانٍ يقول لمن هي. والرقمُ الضريبيُّ ليس هنا — مكانُه تذييلُ الورقة
    حيث يُطلب في التدقيق، انظر `partials/docfoot`.

    وتُرشَّح عند بنائها: طرفٌ بلا سطرٍ واحد لا يُطبع عنوانُه — وخانةٌ خاوية
    تحت «المورّد» تُقرأ حقلًا نُسي.

    المتغيّر: `$parties` قائمةُ `['cap' => ..., 'lines' => [...]]`.
