import { describe, expect, it } from 'vitest';

import { DEVICE_WIDTH, previewFit } from '@/Pages/Admin/Website/ThemeEditor';

/**
 * قاعدةُ تصغير المعاينة — الحسابُ وحدَه، بلا شجرةٍ ولا متصفّح.
 *
 * ═══ وما يُحرَس ═══
 *
 * أنّ الإطار يُرسم بعرض الجهاز كاملًا ثمّ يُصغَّر ليسع العمود — لا أن
 * يُقصَّ عرضُه إلى عرض العمود. والفرقُ بينهما هو الفرقُ بين معاينةٍ تُري
 * التاجرَ ما يراه زبونُه، وأخرى تُريه تخطيطَ الهاتف وتُسمّيه كمبيوتر.
 */
describe('قاعدةُ تصغير المعاينة', () => {
    /** عمودٌ أضيقُ من الجهاز: النسبةُ بينهما، لا واحدٌ ولا صفر */
    it('تُصغّر بقدر ضيق العمود', () => {
        expect(previewFit(820, 540)).toBeCloseTo(540 / 820, 10);
        expect(previewFit(1280, 766)).toBeCloseTo(766 / 1280, 10);
    });

    /**
     * ولا تُكبّر أبدًا.
     *
     * هاتفٌ عرضُه ٣٩٠ في عمودٍ عرضُه ٥٤٠ يبقى ٣٩٠ — ولو نُفخ لرأى التاجرُ
     * حروفًا أكبرَ ممّا يراها زبونُه، وهي الكذبةُ التي تُبنى عليها قرارات.
     */
    it('ولا تُكبّر جهازًا أضيقَ من العمود', () => {
        expect(previewFit(390, 540)).toBe(1);
        expect(previewFit(820, 2000)).toBe(1);
    });

    /** والمساواةُ واحدٌ تمامًا — لا ٠٫٩٩٩ يترك خيطًا أبيض */
    it('وعمودٌ بعرض الجهاز تمامًا يردّ الواحد', () => {
        expect(previewFit(820, 820)).toBe(1);
    });

    /**
     * وعمودٌ لم يُقَس بعد يردّ الواحدَ لا القسمةَ على صفر.
     *
     * وهي حالُ أوّل رسمةٍ قبل أن يقيس `ResizeObserver`، وحالُ jsdom دائمًا.
     * ولولا الردُّ لخرج `Infinity` فصار عرضُ الصندوق `NaNpx`.
     */
    it('وعمودٌ لم يُقَس بعد يردّ الواحد', () => {
        expect(previewFit(820, 0)).toBe(1);
        expect(previewFit(820, -5)).toBe(1);
    });

    /** والمقاساتُ الثلاثةُ مختلفةٌ فعلًا — وإلّا فالأزرارُ زينة */
    it('والمقاساتُ الثلاثةُ ثلاثةٌ لا واحد', () => {
        const w = Object.values(DEVICE_WIDTH);

        expect(new Set(w).size).toBe(3);
        expect(DEVICE_WIDTH.desktop).toBeGreaterThan(DEVICE_WIDTH.tablet);
        expect(DEVICE_WIDTH.tablet).toBeGreaterThan(DEVICE_WIDTH.phone);
    });
});
